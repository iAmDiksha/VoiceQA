// Test Real Hinglish Request through running Vite dev server endpoint
const transcript = 'Login करने के बाद dashboard पे refresh करती हूँ तो session expire हो जाता है और मुझे वापस login page पे भेज देता है।';

async function testFullRoundTrip() {
  console.log('Sending real Hinglish transcript to http://localhost:5173/.netlify/functions/generate-report ...');

  const res = await fetch('http://localhost:5173/.netlify/functions/generate-report', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      transcript,
      model: 'gemini-3.5-flash',
    }),
  });

  console.log('HTTP Status:', res.status);
  const data = await res.json();
  console.log('Backend response success:', data.success);
  console.log('Model used:', data.modelUsed);
  console.log('Parsed Bug Title:', data.data?.title);
  console.log('Severity:', data.data?.severity);
  console.log('Component:', data.data?.component);
  console.log('Steps to Reproduce:', data.data?.stepsToReproduce);
  console.log('Expected Result:', data.data?.expectedResult);
  console.log('Actual Result:', data.data?.actualResult);
  console.log('Test Case ID:', data.data?.testCase?.id);
  console.log('Playwright Snippet Preview:\n', data.data?.testCase?.automationSnippet);

  if (data.success && data.modelUsed) {
    console.log('\n🌟 CONFIRMED: Response was generated by real Gemini AI model:', data.modelUsed);
  } else {
    console.log('\n⚠️ FALLBACK or ERROR:', data.error);
    process.exit(1);
  }
}

testFullRoundTrip().catch((err) => {
  console.error('Test error:', err);
  process.exit(1);
});
